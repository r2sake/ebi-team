import { createRequire } from "node:module";
import { writeFileSync, appendFileSync } from "node:fs";
const require = createRequire("/Users/yoimaro/workspace/GitHub/ebi-team/package.json");
const pty = require("node-pty");
const REPO="/Users/yoimaro/workspace/GitHub/ebi-team";
const WT=REPO+"/.worktrees/ebi-ebiteam-poc-codex";
const form=process.argv[2], OUTF=process.argv[3];
writeFileSync(OUTF,"");
let trust=[];
if(form==="a") trust=["-c",`projects={"${REPO}"={trust_level="trusted"},"${WT}"={trust_level="trusted"}}`];
if(form==="b") trust=["-c",`projects.'${REPO}'.trust_level="trusted"`];
if(form==="c") trust=["-c",`trust_level="trusted"`];
if(form==="d") trust=["-c",`sandbox_workspace_write.trust=true`];
const args=["--no-alt-screen","-s","read-only","-a","never","-c","disable_paste_burst=true","-c","check_for_update_on_startup=false",...trust];
const t0=Date.now();
const p=pty.spawn("codex",args,{name:"xterm-256color",cols:100,rows:30,cwd:WT,env:process.env});
console.log("pid",p.pid,"form",form);
p.onData(d=>appendFileSync(OUTF,d));
p.onExit(e=>{console.log("EXIT t=",Date.now()-t0,JSON.stringify(e));process.exit(0);});
setTimeout(()=>{try{p.kill();}catch{};setTimeout(()=>process.exit(0),300);},8000);
